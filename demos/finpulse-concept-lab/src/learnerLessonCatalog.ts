export type LearnerLessonGroup = 'message' | 'deadline'

export type LearnerPracticeKind =
  | 'status'
  | 'sources'
  | 'comparison'
  | 'roles'
  | 'thread'
  | 'revision'
  | 'evidence'
  | 'deadline'

export type LearnerPromptMode = 'single' | 'multiple'

export interface LearnerChoiceOption {
  id: string
  label: string
  body?: string
}

export interface LearnerPrompt {
  id: string
  legend: string
  options: readonly [LearnerChoiceOption, LearnerChoiceOption, ...LearnerChoiceOption[]]
  expected: readonly [string, ...string[]]
  mode?: LearnerPromptMode
}

export interface LearnerLabelBodyItem {
  label: string
  body: string
}

export interface LearnerStoryScreen {
  title: string
  paragraphs: readonly [string, string, string?, string?, string?]
}

export interface LearnerFocusScreen {
  title: string
  lead: string
  items: readonly [LearnerLabelBodyItem, LearnerLabelBodyItem, ...LearnerLabelBodyItem[]]
}

export interface LearnerPracticeScreen {
  kind: LearnerPracticeKind
  title: string
  notice?: string
  contextItems: readonly LearnerLabelBodyItem[]
  prompts: readonly [LearnerPrompt, ...LearnerPrompt[]]
}

export interface LearnerFeedbackScreen {
  successTitle: string
  nuanceTitle: string
  paragraphs: readonly [string, ...string[]]
  facts: readonly LearnerLabelBodyItem[]
}

export interface LearnerOutcomeScreen {
  title: string
  paragraphs: readonly [string, ...string[]]
  resultLabel?: string
  resultItems?: readonly LearnerLabelBodyItem[]
}

export interface LearnerTransferFeedback {
  success: string
  nuance: string
  copy: string
}

export interface LearnerTransferScreen {
  title: string
  scenario: string
  prompts: readonly [LearnerPrompt, LearnerPrompt?]
  feedback: LearnerTransferFeedback
}

export interface LearnerSummaryScreen {
  title: string
  items: readonly [LearnerLabelBodyItem, LearnerLabelBodyItem, LearnerLabelBodyItem]
  takeaway: string
}

export interface LearnerLesson {
  slug: LearnerLessonSlug
  title: string
  duration: string
  group: LearnerLessonGroup
  labDescription: string
  goal: string
  introLead: string
  startLabel: string
  story: LearnerStoryScreen
  focus: LearnerFocusScreen
  practice: LearnerPracticeScreen
  feedback: LearnerFeedbackScreen
  outcome: LearnerOutcomeScreen
  transfer: LearnerTransferScreen
  summary: LearnerSummaryScreen
}

